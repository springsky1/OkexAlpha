#!/usr/bin/env bash
# 由 .run/okx.env 生成 .run/start.bat（单一口径，避免口令在 bat 与 env 之间漂移）。
# 用法：scripts/gen-run-config.sh   （生成后需重启服务才生效）
set -euo pipefail
root="$(cd "$(dirname "$0")/.." && pwd)"
env_file="$root/.run/okx.env"
run_dir="$root/.run"
java_bin="D:\\Program Files\\Eclipse Adoptium\\jdk-25.0.5.8-hotspot\\bin\\java.exe"

[ -f "$env_file" ] || { echo "missing $env_file" >&2; exit 1; }

set -a
# shellcheck disable=SC1090
source "$env_file"
set +a

{
  echo '@echo off'
  echo 'rem generated by scripts/gen-run-config.sh from okx.env -- do not edit by hand'
  echo 'cd /d D:\workplace\Github\OkexAlpha\.run'
  # set "K=V" 的引号形式：值里含空格/&/| 时不会被 cmd 截断（set K=V& 会被当成命令分隔符）。
  [ -n "${OKX_DB_PASSWORD:-}" ] && echo "set \"OKX_DB_PASSWORD=$OKX_DB_PASSWORD\""
  [ -n "${OKX_MASTER_KEY:-}" ] && echo "set \"OKX_MASTER_KEY=$OKX_MASTER_KEY\""
  [ -n "${OKX_KEY_LABEL:-}" ] && echo "set \"OKX_KEY_LABEL=$OKX_KEY_LABEL\""
  echo "\"$java_bin\" -jar app.jar --server.port=${PORT:-18080} >> app.log 2>&1"
} > "$run_dir/start.bat"

echo "wrote $run_dir/start.bat"
